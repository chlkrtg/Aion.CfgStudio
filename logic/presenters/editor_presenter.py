"""Presenter для страницы редактора cfg.

Ленивая загрузка: строки строятся только для видимых команд
(под текущий фильтр). Состояние всех команд хранится в self._state -
это позволяет сохранять и логировать изменения скрытых команд тоже.
"""
from PyQt6.QtCore import Qt
from PyQt6.QtWidgets import QMessageBox, QListWidgetItem

from logic.presenters.base_presenter import BasePresenter
from logic.core.i18n import t
from logic.widgets.dialogs import ask_yes_no_cancel, ask_yes_no

def _state_val(item) -> int:
    state = item.checkState()
    if hasattr(state, "value"):
        return state.value
    return int(state)


class EditorPresenter(BasePresenter):
    """Логика страницы редактора."""

    def __init__(self, view, service):
        super().__init__(view)
        self.service = service

        self.config_id: int | None = None
        self.server_id: int | None = None

        # кэш данных из БД
        self._commands: list | None = None
        self._prefixes: dict | None = None

        # снимок состояния ВСЕХ команд: {cmd_id: (use, value)}
        self._state: dict[int, tuple[int, str | None]] = {}

        # что сейчас в таблице
        self._cmd_by_row: dict[int, dict] = {}
        self._group_rows: dict[str, list[int]] = {}
        self._group_header_row: dict[str, int] = {}

    # ============ контекст ============

    def set_context(self, config_id, server_id):
        self.config_id = config_id
        self.server_id = server_id

    # ============ жизненный цикл ============

    def on_enter(self):
        self._commands = None
        self._prefixes = None

        self.view.editSearch.blockSignals(True)
        self.view.editSearch.clear()
        self.view.editSearch.blockSignals(False)

        self.view.listPrefixes.blockSignals(True)
        self.view.listPrefixes.setCurrentRow(0)
        self.view.listPrefixes.blockSignals(False)

        self.refresh()

    def on_leave(self) -> bool:
        """Возвращает False, если пользователь отменил уход.

        Если есть несохранённые изменения, спрашивает:
          Yes - сохранить и уйти
          No - уйти без сохранения
          Cancel - остаться
        """
        if self.config_id is None:
            if self._has_checked_commands():
                ans = ask_yes_no_cancel(
                    self.view,
                    t("editor.dialog.new.title"),
                    t("editor.dialog.new.text"),
                )
                if ans == "cancel":
                    return False
                if ans == "yes":
                    self.apply_silent()
            return True

        has_changes = self._has_unsaved_changes()

        if has_changes:
            ans = ask_yes_no_cancel(
                self.view,
                t("editor.dialog.unsaved.title"),
                t("editor.dialog.unsaved.text")
            )
            if ans == "cancel":
                return False
            if ans == "yes":
                self._save_current_state()
        return True

    def _has_unsaved_changes(self) -> bool:
        """Проверяет, отличается ли текущее состояние таблицы от БД.

        Сравнивает:
          - текущий _state (собранный из таблицы)
          - сохранённый saved_values (из ConfigValues)
        """
        if self.config_id is None:
            return False

        self._sync_state_from_table()

        current_state = dict(self._state)
        saved = self.service.saved_values(self.config_id)

        # нормализуем и сравниваем
        all_ids = set(current_state) | set(saved)
        for cmd_id in all_ids:
            cur = current_state.get(cmd_id, (0, None))
            old = saved.get(cmd_id, (0, None))

            cur_use, cur_val = cur
            old_use, old_val = old

            # нормализация: None и "" считаем одинаковыми
            cur_val_norm = (
                None if not cur_use or cur_val is None
                else str(cur_val).strip()
            )
            old_val_norm = (
                None if not old_use or old_val is None
                else str(old_val).strip()
            )

            if cur_val_norm != old_val_norm:
                return True

        return False

    def _save_current_state(self):
        """Сохраняет content и ConfigValues без диалогов.

        Обновляет и текст cfg, и значения команд - они синхронны.
        """
        if self.config_id is None:
            return

        # 1. собираем отмеченные команды
        values = self._collect_values()

        # 2. формируем content
        if values:
            content = self.service.collect_content(values)
        else:
            content = (
                "-- [System-Configuration Ver1.0]\n"
                "-- Attention: This file is generated by the system, "
                "do not modify!\n"
            )

        # 3. старое состояние для логов
        old_state = self.service.saved_values(self.config_id)

        # 4. обновляем content
        self.service.config_repo.update(self.config_id, content)

        # 5. обновляем ConfigValues
        self._save_values_to_db()

        # 6. логи
        self._write_logs(old_state)

    # ============ refresh ============

    def refresh(self):
        self._update_file_label()
        self._load_prefixes()
        self._load_commands_cache()
        self._load_state_snapshot()
        self.apply_filters(sync=False)

    def _update_file_label(self):
        if self.config_id is None:
            self.view.lblFileName.setText(t("editor.lbl_file_new"))
            return
        cfg = self.service.config_repo.get(self.config_id)
        if cfg:
            self.view.lblFileName.setText(
                t("editor.lbl_file").format(name=cfg["filename"])
            )
        else:
            self.view.lblFileName.setText(t("editor.lbl_file_none"))

    def _load_prefixes(self):
        view = self.view
        current_code = None
        item = view.listPrefixes.currentItem()
        if item is not None and not item.text().startswith("Все"):
            current_code = item.text().split(" ")[0]

        view.listPrefixes.blockSignals(True)
        view.listPrefixes.clear()
        all_item = QListWidgetItem(t("editor.prefix_all"))
        all_item.setData(Qt.ItemDataRole.UserRole, "__ALL__")
        view.listPrefixes.addItem(all_item)

        if self._prefixes is None:
            self._prefixes = {
                row["id"]: dict(row)
                for row in self.service.all_prefixes()
            }

        for row in self._prefixes.values():
            view.listPrefixes.addItem(f"{row['code']} — {row['name']}")

        target_row = 0
        if current_code is not None:
            for i in range(view.listPrefixes.count()):
                if view.listPrefixes.item(i).text().startswith(
                    current_code + " "
                ):
                    target_row = i
                    break
        view.listPrefixes.setCurrentRow(target_row)
        view.listPrefixes.blockSignals(False)

    def _load_commands_cache(self):
        if self._commands is None:
            self._commands = list(self.service.all_commands())
        if self._prefixes is None:
            self._prefixes = {
                row["id"]: dict(row)
                for row in self.service.all_prefixes()
            }

    def _load_state_snapshot(self):
        """Загружает ВСЕ значения cfg в self._state."""
        self._state = {}
        if self.config_id is None:
            for cmd in self._commands:
                self._state[cmd["id"]] = (0, None)
            return

        saved = self.service.saved_values(self.config_id)
        for cmd in self._commands:
            cmd_id = cmd["id"]
            if cmd_id in saved:
                self._state[cmd_id] = saved[cmd_id]
            else:
                self._state[cmd_id] = (0, None)

    # ============ фильтры ============
    def apply_filters(self, sync=True):
        """Определяет видимые команды и перестраивает таблицу.

        sync=True - синхронизировать _state с текущей таблицей.
        sync=False - не синхронизировать (при входе на страницу).
        """
        if sync:
            self._sync_state_from_table()

        view = self.view
        prefix_item = view.listPrefixes.currentItem()
        prefix_code = None
        if prefix_item is not None:
            marker = prefix_item.data(Qt.ItemDataRole.UserRole)
            if marker != "__ALL__":
                prefix_code = prefix_item.text().split(" ")[0]

        search = view.editSearch.text().lower().strip()

        visible = []
        for cmd in self._commands:
            pid = cmd["prefix_id"]
            if pid is None or pid not in self._prefixes:
                continue
            pcode = self._prefixes[pid]["code"]

            if prefix_code is not None and pcode != prefix_code:
                continue
            if search and search not in cmd["key_name"].lower():
                continue

            visible.append((cmd, pcode))

        # обновить счётчик ПОСЛЕ фильтрации
        self.view.set_command_count(len(visible))

        self._rebuild_table(visible)

    def _rebuild_table(self, visible_commands):
        view = self.view
        t = view.tableCommands

        self._cmd_by_row.clear()
        self._group_rows.clear()
        self._group_header_row.clear()

        # посчитать финальный размер
        rows_total = 0
        current_prefix = None
        for cmd, pcode in visible_commands:
            if pcode != current_prefix:
                rows_total += 1
                current_prefix = pcode
            rows_total += 1

        # посчитать видимые/всего по каждой группе
        group_visible = {}
        group_total = {}
        for cmd, pcode in visible_commands:
            group_visible[pcode] = group_visible.get(pcode, 0) + 1

        for cmd in self._commands:
            pid = cmd["prefix_id"]
            if pid is None or pid not in self._prefixes:
                continue
            pcode = self._prefixes[pid]["code"]
            group_total[pcode] = group_total.get(pcode, 0) + 1

        t.blockSignals(True)
        t.clearContents()
        t.setRowCount(rows_total)

        current_prefix = None
        row = 0
        for cmd, pcode in visible_commands:
            prefix = self._prefixes[cmd["prefix_id"]]
            if pcode != current_prefix:
                # ← ВОТ ЗДЕСЬ: передаём счётчики
                view.make_group_header(
                    row, pcode, prefix["name"],
                    visible_count=group_visible.get(pcode, 0),
                    total_count=group_total.get(pcode, 0),
                )
                self._group_header_row[pcode] = row
                self._group_rows[pcode] = []
                current_prefix = pcode
                row += 1

            view.fill_command_row(row, cmd)
            self._cmd_by_row[row] = {"command": cmd, "group_code": pcode}
            self._group_rows[pcode].append(row)

            use, val = self._state.get(cmd["id"], (0, None))
            chk_item = t.item(row, 0)
            val_item = t.item(row, 2)
            if use and val is not None:
                chk_item.setCheckState(Qt.CheckState.Checked)
                val_item.setText(str(val))
                view.set_value_enabled(row, True)
            else:
                chk_item.setCheckState(Qt.CheckState.Unchecked)
                view.set_value_enabled(row, False)
            row += 1

        t.blockSignals(False)
        self._update_group_checks()

    # ============ синхронизация состояния ============

    def _sync_state_from_table(self):
        t = self.view.tableCommands
        for row, info in self._cmd_by_row.items():
            cmd_id = info["command"]["id"]
            chk_item = t.item(row, 0)
            val_item = t.item(row, 2)
            if chk_item is None or val_item is None:
                continue
            state_val = _state_val(chk_item)
            if state_val == 2:
                val = val_item.text().strip()
                self._state[cmd_id] = (1, val)
            else:
                self._state[cmd_id] = (0, None)

    # ============ групповые чекбоксы ============

    def _update_group_checks(self):
        t = self.view.tableCommands
        for code, chk_row in self._group_header_row.items():
            rows = self._group_rows.get(code, [])
            checked = 0
            total = 0
            for r in rows:
                chk_item = t.item(r, 0)
                if chk_item is not None:
                    total += 1
                    state_val = _state_val(chk_item)
                    if state_val == 2:
                        checked += 1

            if total == 0 or checked == 0:
                state = Qt.CheckState.Unchecked
            elif checked == total:
                state = Qt.CheckState.Checked
            else:
                state = Qt.CheckState.PartiallyChecked

            group_item = t.item(chk_row, 0)
            if group_item is not None:
                t.blockSignals(True)
                group_item.setCheckState(state)
                t.blockSignals(False)

    # ============ сохранение ============

    def _save_values_to_db(self):
        """Сохраняет ВСЕ значения (и видимые, и скрытые)."""
        if self.config_id is None:
            return

        self._sync_state_from_table()

        rows = []
        for cmd in self._commands:
            cmd_id = cmd["id"]
            use, val = self._state.get(cmd_id, (0, None))
            rows.append((cmd_id, use, val))

        self.service.save_values(self.config_id, rows)

    def _has_checked_commands(self) -> bool:
        self._sync_state_from_table()
        return any(use for use, _ in self._state.values())

    # ============ сборка content ============

    def _collect_values(self) -> dict[str, str]:
        self._sync_state_from_table()

        values = {}
        for cmd in self._commands:
            use, val = self._state.get(cmd["id"], (0, None))
            if use and val is not None:
                values[cmd["key_name"]] = val
        return values

    # ============ применение ============

    def apply_silent(self) -> bool:
        values = self._collect_values()
        if not values:
            return False

        content = self.service.collect_content(values)

        try:
            # 1. старое состояние из БД
            old_state = {}
            if self.config_id is not None:
                saved = self.service.saved_values(self.config_id)
                for cmd in self._commands:
                    cmd_id = cmd["id"]
                    if cmd_id in saved:
                        old_state[cmd_id] = saved[cmd_id]
                    else:
                        old_state[cmd_id] = (0, None)
            else:
                for cmd in self._commands:
                    old_state[cmd["id"]] = (0, None)

            # 2. создать или обновить cfg
            self.config_id = self.service.ensure_config(
                self.config_id, self.server_id,
                "system.cfg", content,
            )

            # 3. синхронизировать и сохранить
            self._sync_state_from_table()
            self._save_values_to_db()

            # 4. логи
            self._write_logs(old_state)

            return True
        except Exception as exc:
            print(f"[EditorPresenter] apply_silent failed: {exc}")
            return False

    def on_apply(self):
        values = self._collect_values()
        if not values:
            QMessageBox.information(
                self.view,
                t("editor.info.nothing"),
                t("editor.info.nothing.text"),
            )
            return

        if not self.apply_silent():
            QMessageBox.critical(
                self.view,
                t("editor.error.save"),
                t("editor.error.save.text"),
            )
            return

        QMessageBox.information(
            self.view,
            t("editor.info.done"),
            t("editor.dialog.save.text"),
        )
        win = self.view.window()
        win.go_main(win.current_server_id)

    def on_item_changed(self, item):
        """Вызывается при ЛЮБОМ изменении ячейки.

        Обрабатываем два случая:
          1. Изменился чекбокс команды → обновить групповой чекбокс.
          2. Изменился групповой чекбокс → отметить/снять все видимые
             в группе И активировать/деактивировать их ячейки значений.
        """
        if item.column() != 0:
            return

        t = self.view.tableCommands
        marker = item.data(Qt.ItemDataRole.UserRole)
        if marker is None:
            return

        # 1. групповой чекбокс
        if isinstance(marker, str) and marker.startswith("GROUP:"):
            code = marker[6:]
            state = item.checkState()
            state_val = state.value if hasattr(state, "value") else int(state)

            rows = self._group_rows.get(code, [])

            t.blockSignals(True)
            try:
                for r in rows:
                    chk_item = t.item(r, 0)
                    if chk_item is None:
                        continue
                    if state_val == 2:
                        chk_item.setCheckState(Qt.CheckState.Checked)
                    elif state_val == 0:
                        chk_item.setCheckState(Qt.CheckState.Unchecked)
            finally:
                t.blockSignals(False)

            # активировать / деактивировать value
            for r in rows:
                chk_item = t.item(r, 0)
                if chk_item is None:
                    continue
                state_val = _state_val(chk_item)
                self.view.set_value_enabled(r, state_val == 2)

            self._update_group_checks()
            return

        # 2. чекбокс команды
        if isinstance(marker, str) and marker.startswith("CMD:"):
            row = t.row(item)
            state = item.checkState()
            state_val = state.value if hasattr(state, "value") else int(state)
            checked = (state_val == 2)
            self.view.set_value_enabled(row, checked)
            self._update_group_checks()
            return

    def on_make_defaults(self):
        """Сохраняет значения отмеченных команд как новые дефолты.

        Берёт только команды с непустым значением.
        """
        self._sync_state_from_table()

        updates = []
        for cmd in self._commands:
            use, val = self._state.get(cmd["id"], (0, None))
            if not use:
                continue
            if val is None:
                continue
            val_str = str(val).strip()
            if not val_str:
                continue
            updates.append((cmd["id"], val_str))

        if not updates:
            QMessageBox.warning(
                self.view,
                t("editor.info.nothing"),
                t("editor.info.nothing.text"),
            )
            return

        ans = ask_yes_no(
            self.view,
            t("editor.make_defaults.title"),
            t("editor.make_defaults.text").format(n=len(updates))
        )
        if not ans:
            return

        try:
            self.service.make_defaults(updates)
        except Exception as exc:
            QMessageBox.critical(
                self.view,
                t("editor.error.save"),
                str(exc),
            )
            return

        # перечитать _commands — дефолты изменились в БД
        self._commands = None
        self._load_commands_cache()
        self.apply_filters(sync=False)

        QMessageBox.information(
            self.view,
            t("editor.info.done"),
            t("editor.make_defaults.done").format(n=len(updates)),
        )

    def reset_all(self):
        """Сброс к стандартным с диалогом.

        Спрашивает: только значения / значения + выбор / отмена.
        Затрагивает только видимые команды с default_value.
        """
        t_table = self.view.tableCommands

        # собрать видимые команды с дефолтом
        rows_with_default = []
        for row, info in self._cmd_by_row.items():
            cmd = info["command"]
            default_value = cmd["default_value"]
            if default_value is None or str(default_value).strip() == "":
                continue
            rows_with_default.append((row, cmd, default_value))

        if not rows_with_default:
            QMessageBox.information(
                self.view,
                t("editor.reset_dialog.title"),
                t("editor.reset_dialog.nothing"),
            )
            return

        # диалог с тремя кнопками
        msg = QMessageBox(self.view)
        msg.setWindowTitle(t("editor.reset_dialog.title"))
        msg.setText(
            t("editor.reset_dialog.text").format(n=len(rows_with_default))
        )
        msg.setIcon(QMessageBox.Icon.Question)

        btn_values = msg.addButton(
            t("editor.reset_dialog.btn_values"),
            QMessageBox.ButtonRole.AcceptRole,
        )
        btn_all = msg.addButton(
            t("editor.reset_dialog.btn_all"),
            QMessageBox.ButtonRole.AcceptRole,
        )
        msg.addButton(
            t("editor.btn_cancel"),
            QMessageBox.ButtonRole.RejectRole,
        )

        msg.exec()
        clicked = msg.clickedButton()

        if clicked == btn_values:
            reset_selection = False
        elif clicked == btn_all:
            reset_selection = True
        else:
            return  # отмена

            # применить
        t_table.blockSignals(True)

        if reset_selection:
            # Вариант A: с дефолтом — checked + дефолт, без дефолта — unchecked + пусто
            for row, info in self._cmd_by_row.items():
                cmd = info["command"]
                default_value = cmd["default_value"]

                has_default = (
                        default_value is not None
                        and str(default_value).strip() != ""
                )

                chk_item = t_table.item(row, 0)
                val_item = t_table.item(row, 2)
                if chk_item is None or val_item is None:
                    continue

                if has_default:
                    chk_item.setCheckState(Qt.CheckState.Checked)
                    val_item.setText(str(default_value))
                    self.view.set_value_enabled(row, True)
                else:
                    chk_item.setCheckState(Qt.CheckState.Unchecked)
                    val_item.setText("")
                    self.view.set_value_enabled(row, False)
        else:
            # Только значения: галочки не трогаем, значения = дефолт
            # (только у тех, у кого дефолт есть)
            for row, cmd, default_value in rows_with_default:
                val_item = t_table.item(row, 2)
                if val_item is not None:
                    val_item.setText(str(default_value))

                # синхронизировать editable с текущим состоянием галки
                chk_item = t_table.item(row, 0)
                if chk_item is not None:
                    state = chk_item.checkState()
                    state_val = state.value if hasattr(state, "value") else int(state)
                    checked = (state_val == 2)
                    self.view.set_value_enabled(row, checked)

        t_table.blockSignals(False)

        self._update_group_checks()

        QMessageBox.information(
            self.view,
            t("editor.info.done"),
            t("editor.reset_dialog.done").format(
                n=len(rows_with_default)
            ),
        )

    def cancel(self):
        win = self.view.window()
        win.go_main(win.current_server_id)

    # ============ логи ============

    def _write_logs(self, old_state: dict):
        if self.config_id is None:
            return

        id_to_key = {
            cmd["id"]: cmd["key_name"]
            for cmd in self._commands
        }

        changes = []
        for cmd_id, (old_use, old_val) in old_state.items():
            new_use, new_val = self._state.get(cmd_id, (0, None))

            old_norm = old_val if old_use else None
            new_norm = new_val if new_use else None

            old_str = None if old_norm is None else str(old_norm).strip()
            new_str = None if new_norm is None else str(new_norm).strip()

            if old_str == new_str:
                continue

            key = id_to_key.get(cmd_id)
            if key is None:
                continue

            old_display = old_str if old_str is not None else t("logs.value.removed")
            new_display = new_str if new_str is not None else t("logs.value.removed")

            changes.append((key, old_display, new_display))

        if not changes:
            return

        try:
            self.service.write_logs(self.config_id, changes)
        except Exception as exc:
            print(f"[EditorPresenter] write_logs failed: {exc}")